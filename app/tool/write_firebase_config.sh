#!/usr/bin/env bash
# Writes web/firebase-config.js from a flavor file, for `web/firebase-messaging-sw.js`
# (research R26). The values are public identifiers; they are already in the bundle through
# --dart-define-from-file.
#
# Usage: ./tool/write_firebase_config.sh env/prod.json
set -euo pipefail
cd "$(dirname "$0")/.."

flavor="${1:-env/prod.json}"
if [[ ! -f "$flavor" ]]; then
  echo "no such flavor file: $flavor" >&2
  exit 1
fi

python3 - "$flavor" > web/firebase-config.js <<'PY'
import json, sys
values = json.load(open(sys.argv[1], encoding='utf-8'))
config = {
    'apiKey': values.get('FIREBASE_API_KEY', ''),
    'appId': values.get('FIREBASE_WEB_APP_ID', ''),
    'messagingSenderId': values.get('FIREBASE_MESSAGING_SENDER_ID', ''),
    'projectId': values.get('FIREBASE_PROJECT_ID', ''),
    'authDomain': values.get('FIREBASE_AUTH_DOMAIN', ''),
    'storageBucket': values.get('FIREBASE_STORAGE_BUCKET', ''),
}
print('/* Generated by tool/write_firebase_config.sh from %s. Public identifiers only. */' % sys.argv[1])
print('self.MADAR_FIREBASE_CONFIG = %s;' % json.dumps(config, ensure_ascii=False, indent=2))
PY

echo "wrote web/firebase-config.js from $flavor"
