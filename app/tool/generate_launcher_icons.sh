#!/usr/bin/env bash
# Renders the launcher icons (Android legacy + adaptive, PWA, favicon) from the brand mark in
# madar-design/design-system/components/Logo/mark.svg (a 32-unit grid), composed as in the Play
# icon export: 512-unit art with the mark at 400/512 on the `bg` (dark) ground, and two faint
# rings. Needs rsvg-convert (librsvg). Run from app/.
set -euo pipefail

readonly GROUND='#07090C'
readonly VOLT='#C8F542'
readonly BODY='#F1F4F7'
readonly RING_OUTER='#11161C'
readonly RING_INNER='#161B22'
readonly RES=android/app/src/main/res
readonly TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# The mark alone on its 32-unit grid. $1 ring colour, $2 planet and satellite colour.
mark() {
  cat <<EOF
<defs><mask id="near-band" maskUnits="userSpaceOnUse" x="0" y="0" width="32" height="32"><rect width="32" height="32" fill="#fff"/><path d="M5.616 21.518A11.84 2.86 -28 0 0 26.524 10.402" fill="none" stroke="#000" stroke-width="3.08"/></mask></defs>
<ellipse cx="16.07" cy="15.96" rx="11.84" ry="2.86" fill="none" stroke="$1" stroke-width="1.66" transform="rotate(-28 16.07 15.96)"/>
<circle cx="16" cy="16" r="5.69" fill="$2" mask="url(#near-band)"/>
<g fill="$2" transform="translate(26.47 7.43) rotate(-28)"><rect x="-1.07" y="-1.07" width="2.14" height="2.14" rx=".5"/><rect x="-3.56" y="-.59" width="1.9" height="1.18" rx=".2"/><rect x="1.66" y="-.59" width="1.9" height="1.18" rx=".2"/></g>
EOF
}

# The Play icon's art on a 512-unit square: rings and the mark, no ground. The mark's grid is
# 400 units wide, so its planet sits at the centre.
art() {
  cat <<EOF
<circle cx="256" cy="256" r="245.3" fill="none" stroke="$RING_OUTER" stroke-width="2"/>
<circle cx="256" cy="256" r="209.8" fill="none" stroke="$RING_INNER" stroke-width="2"/>
<g transform="translate(256 256) scale(12.5) translate(-16 -16)">$(mark "$VOLT" "$BODY")</g>
EOF
}

# The rounded tile (legacy launcher, PWA "any"): the export's radius.
cat >"$TMP/tile.svg" <<EOF
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">
<rect width="512" height="512" rx="116" fill="$GROUND"/>
$(art)
</svg>
EOF

# The favicon is too small for the rings: the mark fills its tile.
cat >"$TMP/favicon.svg" <<EOF
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">
<rect width="32" height="32" rx="7" fill="$GROUND"/>
$(mark "$VOLT" "$BODY")
</svg>
EOF

# Full-bleed ground, with the satellite's tip inside the maskable safe circle (40% of the side).
cat >"$TMP/maskable.svg" <<EOF
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">
<rect width="512" height="512" fill="$GROUND"/>
<g transform="translate(256 256) scale(0.9) translate(-256 -256)">$(art)</g>
</svg>
EOF

# Adaptive foreground on the 108dp canvas: the art fills the 72dp visible square, and the
# mark stays inside the 66dp safe circle. The rings live here so the ground stays one colour.
cat >"$TMP/foreground.svg" <<EOF
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108">
<g transform="translate(18 18) scale(0.140625)">$(art)</g>
</svg>
EOF

# Android 13 themed icons tint this layer; only its alpha counts, so no rings.
cat >"$TMP/monochrome.svg" <<EOF
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108">
<g transform="translate(18 18) scale(0.140625) translate(256 256) scale(12.5) translate(-16 -16)">$(mark '#000000' '#000000')</g>
</svg>
EOF

render() { rsvg-convert -w "$2" -h "$2" "$1" -o "$3"; }

for density in mdpi:1 hdpi:1.5 xhdpi:2 xxhdpi:3 xxxhdpi:4; do
  name=${density%%:*}
  scale=${density##*:}
  dir="$RES/mipmap-$name"
  mkdir -p "$dir"
  render "$TMP/tile.svg" "$(awk "BEGIN{print 48*$scale}")" "$dir/ic_launcher.png"
  render "$TMP/foreground.svg" "$(awk "BEGIN{print 108*$scale}")" "$dir/ic_launcher_foreground.png"
  render "$TMP/monochrome.svg" "$(awk "BEGIN{print 108*$scale}")" "$dir/ic_launcher_monochrome.png"
done

mkdir -p "$RES/mipmap-anydpi-v26" "$RES/values"
cat >"$RES/mipmap-anydpi-v26/ic_launcher.xml" <<'EOF'
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_launcher_icons.sh. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome"/>
</adaptive-icon>
EOF
cat >"$RES/values/ic_launcher_background.xml" <<EOF
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_launcher_icons.sh: the bg token (dark). -->
<resources>
    <color name="ic_launcher_background">$GROUND</color>
</resources>
EOF

render "$TMP/tile.svg" 192 web/icons/Icon-192.png
render "$TMP/tile.svg" 512 web/icons/Icon-512.png
render "$TMP/maskable.svg" 192 web/icons/Icon-maskable-192.png
render "$TMP/maskable.svg" 512 web/icons/Icon-maskable-512.png
render "$TMP/favicon.svg" 32 web/favicon.png
