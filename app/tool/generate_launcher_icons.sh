#!/usr/bin/env bash
# Renders the launcher icons (Android legacy + adaptive, PWA, favicon) from the brand mark in
# madar-design/design-system/components.css (`.mk`, a 32-unit grid). Colours are the tokens
# `on-accent` (tile) and `accent` (mark). Needs rsvg-convert (librsvg). Run from app/.
set -euo pipefail

readonly INK='#0A0D0F'
readonly VOLT='#C8F542'
readonly RES=android/app/src/main/res
readonly TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# The mark alone, centred on (16,16) in the 32-unit grid.
mark() {
  local fill=$1
  cat <<EOF
<ellipse cx="16" cy="16" rx="12" ry="5" fill="none" stroke="$fill" stroke-width="1.8" transform="rotate(-28 16 16)"/>
<circle cx="16" cy="16" r="5.2" fill="$fill"/>
<circle cx="26.6" cy="10.4" r="2.1" fill="$fill"/>
EOF
}

# The design's tile: rounded ink square with the mark (legacy launcher, PWA "any", favicon).
cat >"$TMP/tile.svg" <<EOF
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">
<rect width="32" height="32" rx="9" fill="$INK"/>
$(mark "$VOLT")
</svg>
EOF

# Full-bleed ink with the mark inside the maskable safe circle (radius 40% of the side).
cat >"$TMP/maskable.svg" <<EOF
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">
<rect width="32" height="32" fill="$INK"/>
<g transform="translate(16 16) scale(0.85) translate(-16 -16)">$(mark "$VOLT")</g>
</svg>
EOF

# Adaptive foreground on the 108dp canvas: the mark stays inside the 66dp safe circle.
cat >"$TMP/foreground.svg" <<EOF
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108">
<g transform="translate(54 54) scale(2.2) translate(-16 -16)">$(mark "$VOLT")</g>
</svg>
EOF

# Android 13 themed icons tint this layer; only its alpha counts.
sed "s/$VOLT/#000000/g" "$TMP/foreground.svg" >"$TMP/monochrome.svg"

render() { rsvg-convert -w "$2" -h "$2" "$1" -o "$3"; }

for density in mdpi:1 hdpi:1.5 xhdpi:2 xxhdpi:3 xxxhdpi:4; do
  name=${density%%:*}
  scale=${density##*:}
  dir="$RES/mipmap-$name"
  mkdir -p "$dir"
  render "$TMP/tile.svg" "$(awk "BEGIN{print 48*$scale}")" "$dir/ic_launcher.png"
  render "$TMP/foreground.svg" "$(awk "BEGIN{print 108*$scale}")" "$dir/ic_launcher_foreground.png"
  render "$TMP/monochrome.svg" "$(awk "BEGIN{print 108*$scale}")" "$dir/ic_launcher_monochrome.png"
done

mkdir -p "$RES/mipmap-anydpi-v26" "$RES/values"
cat >"$RES/mipmap-anydpi-v26/ic_launcher.xml" <<'EOF'
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_launcher_icons.sh. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome"/>
</adaptive-icon>
EOF
cat >"$RES/values/ic_launcher_background.xml" <<EOF
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_launcher_icons.sh: the on-accent token. -->
<resources>
    <color name="ic_launcher_background">$INK</color>
</resources>
EOF

render "$TMP/tile.svg" 192 web/icons/Icon-192.png
render "$TMP/tile.svg" 512 web/icons/Icon-512.png
render "$TMP/maskable.svg" 192 web/icons/Icon-maskable-192.png
render "$TMP/maskable.svg" 512 web/icons/Icon-maskable-512.png
render "$TMP/tile.svg" 32 web/favicon.png
