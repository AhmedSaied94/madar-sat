// Extracts the admin's icon set from madar-design app.css (.i-<name> mask SVGs) into a TS module.
// Usage (from admin/): node scripts/extract-icons.mjs ../madar-design/admin-react/styles/app.css src/components/Icon/icons.ts
import { readFileSync, writeFileSync } from 'node:fs';

const [cssPath, outPath] = process.argv.slice(2);
const css = readFileSync(cssPath, 'utf8');

const wanted = {
  dashboard: 'dash', ball: 'ball', shield: 'shield', trophy: 'trophy', tv: 'tv', satellite: 'sat',
  certificate: 'cert', mic: 'mic', tower: 'tower', layers: 'layers', database: 'db', flag: 'flag',
  bell: 'bell', users: 'users', history: 'history', logout: 'logout', search: 'search', mail: 'mail',
  lock: 'lock', eye: 'eye', eyeOff: 'eyeoff', alert: 'alert', shieldCheck: 'shieldck', clock: 'clock',
  check: 'check', sort: 'sort', edit: 'edit', dotsVertical: 'dotsv', trash: 'trash', info: 'info', close: 'x',
  plus: 'plus', chevronDown: 'chd', calendar: 'cal',
};

const camel = (name) => name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const attrsOf = (text) => {
  const attrs = {};
  for (const m of text.matchAll(/([a-zA-Z:-]+)='([^']*)'/g)) attrs[camel(m[1])] = m[2];
  return attrs;
};

const out = {};
for (const [name, cls] of Object.entries(wanted)) {
  const m = css.match(new RegExp(`\\.i-${cls}\\{--i:url\\("data:image/svg\\+xml,([^"]+)"\\)\\}`));
  if (!m) throw new Error(`icon not found: ${cls}`);
  const svg = decodeURIComponent(m[1]);
  const root = attrsOf(svg.match(/<svg([^>]*)>/)[1]);
  const children = [...svg.matchAll(/<(path|circle|rect|line|polyline|polygon|ellipse)\b([^>]*?)\/?>/g)].map(
    ([, tag, rest]) => {
      const attrs = attrsOf(rest);
      for (const key of ['fill', 'stroke']) if (attrs[key] && attrs[key] !== 'none') attrs[key] = 'currentColor';
      return [tag, attrs];
    },
  );
  const filled = root.fill && root.fill !== 'none';
  out[name] = { filled: Boolean(filled), strokeWidth: root.strokeWidth ?? null, children };
}

const lines = [
  '// GENERATED by extracting the .i-<name> icons from madar-design/admin-react/styles/app.css.',
  '// Do not edit by hand: re-run scripts/extract-icons.mjs if the design package changes an icon.',
  '',
  "export type IconElement = readonly ['path' | 'circle' | 'rect' | 'line' | 'polyline' | 'polygon' | 'ellipse', Readonly<Record<string, string>>];",
  '',
  'export interface IconDefinition {',
  '  readonly filled: boolean;',
  '  readonly strokeWidth: string | null;',
  '  readonly children: readonly IconElement[];',
  '}',
  '',
  `export const icons = ${JSON.stringify(out, null, 2)} as const satisfies Record<string, IconDefinition>;`,
  '',
  'export type IconName = keyof typeof icons;',
  '',
];
writeFileSync(outPath, lines.join('\n'));
console.log(`wrote ${Object.keys(out).length} icons`);
